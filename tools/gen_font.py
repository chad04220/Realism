# Generates src/ui/font_data.h: a signed-distance-field glyph atlas (ASCII 32..126
# plus a few UI symbols) from DejaVu Sans (Bitstream Vera licence, free to embed).
# SDF text stays crisp at any UI scale; the shader can also thicken it for bold.
#   python tools/gen_font.py [font.ttf] [out.h]
import sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy import ndimage

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
OUT = sys.argv[2] if len(sys.argv) > 2 else "src/ui/font_data.h"
SZ, PAD, SS = 36, 5, 4      # em size in atlas px, padding, supersample
SPREAD = 5.0

# ASCII plus: degree, middle dot, multiply, arrows, bullet, ellipsis, minus, check, warning.
EXTRA = [0xB0, 0xB2, 0xB3, 0xB7, 0xD7, 0x2013, 0x2014, 0x2082, 0x2190, 0x2191, 0x2192, 0x2193, 0x2022, 0x2026, 0x2212, 0x2713, 0x26A1, 0x2248, 0x394]
font = ImageFont.truetype(FONT, SZ * SS)
from fontTools.ttLib import TTFont
cmap = TTFont(FONT).getBestCmap()
codes = list(range(32, 127)) + [c for c in EXTRA if c in cmap]
asc, desc = font.getmetrics()
lineh = (asc + desc) / SS
adv = {c: font.getlength(chr(c)) / SS for c in codes}
cellw = int(np.ceil(max(adv.values()))) + 2 * PAD + 2
cellh = int(np.ceil(lineh)) + 2 * PAD
cols = 16
rows = (len(codes) + cols - 1) // cols
W, H = cols * cellw, rows * cellh
atlas = np.zeros((H, W), np.uint8)
for n, c in enumerate(codes):
    cx, cy = (n % cols) * cellw, (n // cols) * cellh
    img = Image.new("L", (cellw * SS, cellh * SS), 0)
    ImageDraw.Draw(img).text((PAD * SS, PAD * SS), chr(c), font=font, fill=255)
    a = np.array(img) > 127
    din = ndimage.distance_transform_edt(a)
    dout = ndimage.distance_transform_edt(~a)
    sd = (dout - din) / SS
    sd = sd.reshape(cellh, SS, cellw, SS).mean(axis=(1, 3))
    v = np.clip(0.5 - sd / (2 * SPREAD), 0, 1)
    atlas[cy:cy + cellh, cx:cx + cellw] = (v * 255).astype(np.uint8)

with open(OUT, "w", newline="\n") as f:
    f.write("// Generated by tools/gen_font.py from DejaVu Sans (Bitstream Vera licence). Do not edit.\n")
    f.write("#pragma once\n#include <cstdint>\n")
    f.write(f"namespace font {{\nconstexpr int W = {W}, H = {H}, CELLW = {cellw}, CELLH = {cellh}, COLS = {cols}, PAD = {PAD}, EM = {SZ};\n")
    f.write(f"constexpr float ASC = {asc / SS:.3f}f, LINEH = {lineh:.3f}f, SPREAD = {SPREAD}f;\n")
    f.write(f"constexpr int COUNT = {len(codes)};\n")
    f.write("constexpr uint32_t CODES[COUNT] = {" + ",".join(str(c) for c in codes) + "};\n")
    f.write("constexpr float ADV[COUNT] = {" + ",".join(f"{adv[c]:.3f}f" for c in codes) + "};\n")
    # Run-length encode the atlas to keep the header small.
    flat = atlas.flatten()
    rle = []
    i = 0
    while i < len(flat):
        j = i
        while j < len(flat) and flat[j] == flat[i] and j - i < 255:
            j += 1
        rle += [j - i, int(flat[i])]
        i = j
    f.write(f"constexpr int RLE_LEN = {len(rle)};\n")
    f.write("constexpr uint8_t RLE[RLE_LEN] = {\n")
    for k in range(0, len(rle), 40):
        f.write(",".join(str(x) for x in rle[k:k + 40]) + ",\n")
    f.write("};\n}\n")
print(f"{OUT}: {W}x{H}, {len(codes)} glyphs, {len(rle)} rle bytes")
